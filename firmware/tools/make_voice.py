#!/usr/bin/env python3
"""Speaks the base's Mongolian phrases with ElevenLabs into 16 kHz μ-law samples (firmware/voice.h).

The second base (ESP32-S3) has a speaker. The phrases are made here once, on a computer, and built into
the firmware, so the base needs no Wi-Fi and no API key. The key and voice come from ~/.elevenlabs.env
(ELEVENLABS_API_KEY, ELEVENLABS_VOICE_ID), never from the repository.
  python3 firmware/tools/make_voice.py [model]     # default eleven_v4, the first model that speaks Mongolian
"""
import json
import os
import struct
import sys
import urllib.request

OUT = os.path.join(os.path.dirname(__file__), '..', 'voice.h')
# The same voice for the app's demo (Profile › Ухаалаг суурь › Суурийн хоолой, src/components/DevicePanel.ts).
APP = os.path.join(os.path.dirname(__file__), '..', '..', 'public', 'voice')
RATE = 16000
MODEL = sys.argv[1] if len(sys.argv) > 1 else 'eleven_v4'

# "N миллилитр дутуу байна" for 10..190 ml, a phrase each: numbers read far better whole than glued
# from pieces. The firmware rounds what is left to the nearest 10 ml.
TENS = ['Арван', 'Хорин', 'Гучин', 'Дөчин', 'Тавин', 'Жаран', 'Далан', 'Наян', 'Ерэн']
SHORT = [f'{w} миллилитр дутуу байна.' for w in TENS] + ['Зуун миллилитр дутуу байна.'] + \
    [f'Зуун {w.lower()} миллилитр дутуу байна.' for w in TENS]

# Past the day's amount, every drink says by how much: "Анхаар! N миллилитр илүү уусан." for 100..900 ml
# and "мянга гаруй" beyond. The firmware rounds to the nearest 100 ml (at least 100). Steps of 100 keep
# the clips inside the S3's 3 MB app partition.
HUNDREDS = ['Зуун', 'Хоёр зуун', 'Гурван зуун', 'Дөрвөн зуун', 'Таван зуун', 'Зургаан зуун', 'Долоон зуун', 'Найман зуун', 'Есөн зуун']
EXTRA = [f'Анхаар! {w} миллилитр илүү уусан.' for w in HUNDREDS] + ['Анхаар! Мянга гаруй миллилитр илүү уусан.']

# name in C, text
PHRASES = [
    ('kVoiceReady', 'Суурь танигдлаа.'),
    ('kVoiceLinked', 'Сав холбогдлоо.'),
    ('kVoiceReached', 'Өдрийн хэмжээндээ хүрлээ. Сайн байна!'),
    ('kVoiceOver', 'Анхаар! Хязгаараас хэтэрлээ. Цааш уухгүй байгаарай.'),
] + [(f'kVoiceShort{(i + 1) * 10}', text) for i, text in enumerate(SHORT)] + \
    [(f'kVoiceExtra{(i + 1) * 100}', text) for i, text in enumerate(EXTRA)]


def env():
    values = {}
    with open(os.path.expanduser('~/.elevenlabs.env')) as f:
        for line in f:
            if '=' in line:
                k, v = line.strip().split('=', 1)
                values[k] = v
    return values['ELEVENLABS_API_KEY'], values['ELEVENLABS_VOICE_ID']


def speak(text, key, voice, output=f'pcm_{RATE}'):
    request = urllib.request.Request(
        f'https://api.elevenlabs.io/v1/text-to-speech/{voice}?output_format={output}',
        data=json.dumps({'text': text, 'model_id': MODEL, 'language_code': 'mn'}).encode(),
        headers={'xi-api-key': key, 'Content-Type': 'application/json'})
    with urllib.request.urlopen(request) as response:
        raw = response.read()
    return raw if output.startswith('mp3') else list(struct.unpack(f'<{len(raw) // 2}h', raw))


# G.711 μ-law: a byte a sample, half the flash of 16-bit, so every phrase fits the S3's 3 MB app
# partition. voiceTask (firmware.ino) turns each byte back into a 16-bit sample as it plays.
def mulaw(sample):
    sign = 0x80 if sample < 0 else 0
    magnitude = min(-sample if sample < 0 else sample, 32635) + 0x84
    exponent = 7
    while exponent > 0 and not magnitude & (0x4000 >> (7 - exponent)):
        exponent -= 1
    return ~(sign | exponent << 4 | (magnitude >> (exponent + 3)) & 0x0F) & 0xFF


# Silence at either end only delays the base and costs flash; 60 ms is kept so words are not clipped.
def trim(samples, quiet=300, keep=RATE * 60 // 1000):
    loud = [i for i, s in enumerate(samples) if abs(s) > quiet]
    if not loud:
        return samples
    return samples[max(0, loud[0] - keep):loud[-1] + keep]


def main():
    key, voice = env()
    lines = [
        f'// Generated by tools/make_voice.py ({MODEL}): 16 kHz, 8-bit μ-law mono. Do not edit.',
        '#pragma once',
        '#include <stdint.h>',
        '',
        'struct Clip { const uint8_t* samples; uint32_t count; };',
        '',
    ]
    total = 0
    for name, text in PHRASES:
        samples = trim(speak(text, key, voice))
        total += len(samples)
        print(f'{name}: {len(samples) / RATE:.1f} s  {text}')
        body = ','.join(str(mulaw(x)) for x in samples)
        lines.append(f'// {text}')
        lines.append(f'static const uint8_t {name}Data[] = {{{body}}};')
        lines.append(f'const Clip {name} = {{{name}Data, {len(samples)}}};')
    short = ', '.join(f'kVoiceShort{(i + 1) * 10}' for i in range(len(SHORT)))
    lines += ['', '// What is left of the day: kVoiceShort[0] is 10 ml, kVoiceShort[18] is 190 ml.',
              f'const Clip kVoiceShort[] = {{{short}}};', '']
    extra = ', '.join(f'kVoiceExtra{(i + 1) * 100}' for i in range(len(EXTRA)))
    lines += ['// Past the day\'s amount: kVoiceExtra[0] is 100 ml more, kVoiceExtra[9] is over 1,000 ml.',
              f'const Clip kVoiceExtra[] = {{{extra}}};', '']
    with open(OUT, 'w') as f:
        f.write('\n'.join(lines))
    print(f'{len(PHRASES)} phrases, {total / RATE:.0f} s, {total // 1024} KB -> {os.path.normpath(OUT)}')
    os.makedirs(APP, exist_ok=True)
    texts = dict(PHRASES)
    for file, name in [('ready', 'kVoiceReady'), ('short150', 'kVoiceShort150'), ('reached', 'kVoiceReached'), ('over', 'kVoiceOver'), ('extra200', 'kVoiceExtra200')]:
        with open(os.path.join(APP, f'{file}.mp3'), 'wb') as f:
            f.write(speak(texts[name], key, voice, 'mp3_44100_64'))
    print(f'app demo -> {os.path.normpath(APP)}')


if __name__ == '__main__':
    main()
