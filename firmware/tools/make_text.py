#!/usr/bin/env python3
"""Draws the screen's Mongolian words into bitmaps (firmware/text.h).

The OLED's built-in font has only Latin letters, so every fixed word on the screen is drawn here, on a
computer, with a font that has Ө and Ү. Numbers still use the built-in font. Needs Pillow; macOS fonts.
  python3 firmware/tools/make_text.py
"""
import os

from PIL import Image, ImageDraw, ImageFont

OUT = os.path.join(os.path.dirname(__file__), '..', 'text.h')
FONTS = '/System/Library/Fonts/Supplemental/'
SMALL = ImageFont.truetype(FONTS + 'Tahoma.ttf', 10)
# Bold 11 px is the smallest size where ө still reads differently from е.
LABEL = ImageFont.truetype(FONTS + 'Tahoma Bold.ttf', 11)
UNIT = ImageFont.truetype(FONTS + 'Tahoma Bold.ttf', 11)
BIG = ImageFont.truetype(FONTS + 'Tahoma Bold.ttf', 16)

# name in C, text, font. One height per font, so words of the same font share a baseline.
WORDS = [
    ('kTextToday', 'Уусан', LABEL),
    ('kTextWater', 'Саванд', LABEL),
    ('kTextWeight', 'Жин', LABEL),
    ('kTextTare', 'Савны жинг ав', SMALL),
    ('kTextBase', 'Ухаалаг суурь', SMALL),
    ('kTextMl', 'мл', UNIT),
    ('kTextL', 'л', UNIT),
    ('kTextG', 'г', UNIT),
    ('kTextDusal', 'Дусал', BIG),
]


def draw(text, font):
    # Cropped to the font's own ink box (tallest letter to deepest tail), not each word's, so words in one
    # font line up and the screen spends no rows on empty space.
    top = min(font.getbbox(t)[1] for _, t, f in WORDS if f is font)
    bottom = max(font.getbbox(t)[3] for _, t, f in WORDS if f is font)
    width = font.getbbox(text)[2] + 1
    image = Image.new('L', (width, bottom - top), 0)
    ImageDraw.Draw(image).text((0, -top), text, fill=255, font=font)
    return image.point(lambda v: 1 if v > 110 else 0, '1')


def main():
    out = ['#pragma once', '#include <cstdint>', '',
           '// Generated by tools/make_text.py. Do not edit by hand.',
           '// XBM layout for U8g2 drawXBMP: rows of bytes, leftmost pixel in the lowest bit.',
           'struct Text { int width; int height; const uint8_t* bits; };', '']
    for name, text, font in WORDS:
        image = draw(text, font)
        stride = (image.width + 7) // 8
        data = bytearray(stride * image.height)
        for y in range(image.height):
            for x in range(image.width):
                if image.getpixel((x, y)):
                    data[y * stride + x // 8] |= 1 << (x % 8)
        out.append(f'// {text}')
        out.append(f'constexpr uint8_t {name}Bits[{len(data)}] = {{{", ".join(f"0x{b:02x}" for b in data)}}};')
        out.append(f'constexpr Text {name}{{{image.width}, {image.height}, {name}Bits}};')
    with open(OUT, 'w') as f:
        f.write('\n'.join(out) + '\n')
    print(f'wrote {OUT}')


if __name__ == '__main__':
    main()
