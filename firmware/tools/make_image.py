#!/usr/bin/env python3
"""Turns a drawing into the picture the base shows on its OLED (firmware/image.h).

Needs Pillow (pip install pillow). The OLED is one-colour, so only the dark outlines of the drawing light up.
  python3 firmware/tools/make_image.py mascot.png
"""
import os
import sys

from PIL import Image, ImageFilter, ImageOps

HEIGHT = 64  # the whole screen height
OUT = os.path.join(os.path.dirname(__file__), '..', 'image.h')


def main():
    gray = Image.open(sys.argv[1]).convert('L')
    gray = gray.crop(ImageOps.invert(gray).point(lambda v: 255 if v > 25 else 0).getbbox())  # trim the margin
    ink = gray.point(lambda v: 255 if v < 90 else 0)
    # Thicken the lines first, or they vanish when a 1000 px drawing shrinks to 64 px.
    ink = ink.filter(ImageFilter.MaxFilter(max(3, round(max(gray.size) / HEIGHT * 0.6) | 1)))
    scale = HEIGHT / max(gray.size)
    width, height = round(gray.size[0] * scale), round(gray.size[1] * scale)
    lit = ink.resize((width, height), Image.BOX).point(lambda v: 1 if v > 70 else 0, '1')
    # XBM layout for U8g2's drawXBMP: rows of bytes, leftmost pixel in the lowest bit.
    stride = (width + 7) // 8
    data = bytearray(stride * height)
    for y in range(height):
        for x in range(width):
            if lit.getpixel((x, y)):
                data[y * stride + x // 8] |= 1 << (x % 8)
    rows = [', '.join(f'0x{b:02x}' for b in data[i:i + stride]) for i in range(0, len(data), stride)]
    with open(OUT, 'w') as out:
        out.write('#pragma once\n#include <cstdint>\n\n')
        out.write(f'// Generated by tools/make_image.py from {os.path.basename(sys.argv[1])}. Do not edit by hand.\n')
        out.write(f'constexpr int kImageWidth = {width};\nconstexpr int kImageHeight = {height};\n')
        out.write(f'constexpr uint8_t kImage[{len(data)}] = {{\n  ' + ',\n  '.join(rows) + '\n};\n')
    print(f'wrote {OUT}: {width}x{height}')


if __name__ == '__main__':
    main()
